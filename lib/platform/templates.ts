export type CatalogId = (typeof TEMPLATES)[number]['id']

const LEGACY = {
  'do-son': 'trang-dat',
  'nga-sang': 'sang-trang',
  'khac-dau': 'trang-dat',
  'phong-bi': 'trang-dat',
  'tho-ngan': 'sang-trang',
  'tap-chi': 'sang-trang',
  'thuy-tinh': 'anh-sang',
} as const satisfies Record<string, CatalogId>

export type TemplateId = CatalogId | keyof typeof LEGACY

export function isTemplateId(value: unknown): value is TemplateId {
  return typeof value === 'string' && (TEMPLATES.some((item) => item.id === value) || value in LEGACY)
}

export function templateById(id: string) {
  const direct = TEMPLATES.find((item) => item.id === id)
  if (direct) return direct
  const canonical = (id in LEGACY ? LEGACY[id as keyof typeof LEGACY] : id) as string
  return TEMPLATES.find((item) => item.id === canonical) ?? TEMPLATES[0]
}
